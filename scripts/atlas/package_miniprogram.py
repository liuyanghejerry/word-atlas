import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "public" / "atlas"
TARGET = ROOT / "miniprogram"


def copy(source, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)


def main():
    data = json.loads((SOURCE / "kids.json").read_text(encoding="utf-8"))
    output = "// Generated by scripts/atlas/package_miniprogram.py\nmodule.exports = "
    output += json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    (TARGET / "data").mkdir(parents=True, exist_ok=True)
    (TARGET / "data" / "kids.js").write_text(output, encoding="utf-8")
    for entry in data["entries"]:
        word_id = entry["id"]
        copy(SOURCE / "img" / f"{word_id}.webp", TARGET / "media-full" / "img" / f"{word_id}.webp")
        copy(SOURCE / "thumb" / f"{word_id}.webp", TARGET / "media-thumb" / "thumb" / f"{word_id}.webp")
        for folder in ["zh", "zh-ex", "en-us"]:
            package = "media-zh" if folder.startswith("zh") else "media-en"
            copy(SOURCE / "audio" / folder / f"{word_id}.mp3", TARGET / package / "audio" / folder / f"{word_id}.mp3")
        copy(SOURCE / "audio" / "us" / f"{word_id}.mp3", TARGET / "media-en" / "audio" / "us" / f"{word_id}.mp3")
        for index in range(len(entry["words"])):
            copy(SOURCE / "audio" / "zh-word" / f"{word_id}-{index}.mp3", TARGET / "media-zh-word" / "audio" / "zh-word" / f"{word_id}-{index}.mp3")
    for name in ["correct", "wrong", "start", "complete", "flip", "twinkle"]:
        copy(ROOT / "public" / "sfx" / f"{name}.mp3", TARGET / "media-en" / "sfx" / f"{name}.mp3")
    copy(ROOT / "node_modules" / "ts-fsrs" / "dist" / "index.cjs", TARGET / "vendor" / "ts-fsrs.js")
    license_file = ROOT / "node_modules" / "ts-fsrs" / "LICENSE"
    if license_file.exists():
        copy(license_file, TARGET / "vendor" / "ts-fsrs.LICENSE")
    print(f"Packed {len(data['entries'])} cards for WeChat Mini Program")


if __name__ == "__main__":
    main()
